using System.Text.Json;
using AgentSessions.Adapters;
using AgentSessions.Model;
using AgentSessions.Services;
using AgentSessions.Tests.Fixtures;

namespace AgentSessions.Tests;

/// <summary>
/// The real adapters over realistic synthetic sessions (shapes from docs/formats/*-format.md), through the real
/// HandoffBuilder: the handoff must carry the prompt, the commands, the edited files and the conversation, even when
/// the session ends in a long run of tool calls.
/// </summary>
public class HandoffEndToEndTests : IDisposable
{
    private const string Prompt = "Fix the flaky upload test";
    private const string Command = "dotnet test tests/Upload.Tests --filter Retry";
    private const string Plan = "I will run the upload tests first.";
    private const string Done = "Fixed the race in the uploader.";
    private const int TailTools = 50;

    private readonly string _root = SessionFixtures.TempHome();

    public void Dispose() { try { Directory.Delete(_root, true); } catch { } }

    private string Home => Path.Combine(_root, "home");
    private string Edited => Path.Combine(_root, "project", "src", "Uploader.cs");
    private string Project => Path.Combine(_root, "project");

    private static string J(object o) => JsonSerializer.Serialize(o);

    private static string Section(string md, string heading)
    {
        var i = md.IndexOf("\n" + heading + "\n", StringComparison.Ordinal);
        Assert.True(i >= 0, $"missing {heading}");
        var rest = md[(i + heading.Length + 2)..];
        var j = rest.IndexOf("\n## ", StringComparison.Ordinal);
        return j < 0 ? rest : rest[..j];
    }

    private static string Handoff(ISessionAdapter adapter)
    {
        var s = Assert.Single(adapter.Discover().Sessions);
        Assert.Equal(Prompt, s.Title);
        return HandoffBuilder.Build(s, adapter.ReadTranscript(s));
    }

    private void AssertHandoff(string md)
    {
        Assert.Equal($"> {Prompt}\n", Section(md, "## Original request").Trim('\n') + "\n");
        Assert.Contains(Command, Section(md, "## Last commands"));
        Assert.Contains("- " + Edited + "\n", Section(md, "## Files touched"));
        Assert.DoesNotContain("(empty)", md);
        Assert.DoesNotContain("Caveat", md);
        Assert.DoesNotContain("AGENTS.md", md);
        Assert.DoesNotContain("TOOL-OUTPUT", md);   // tool outputs are omitted, only counted
        var recent = Section(md, "## Recent activity");
        Assert.Contains(Prompt, recent);
        Assert.Contains(Plan, recent);
        Assert.Contains(Done, recent);
        Assert.Contains($"{TailTools + 2} tool results omitted", recent);
        var stop = Section(md, "## Where it stopped");
        Assert.Contains(Done, stop);
    }

    [Fact]
    public void Claude_session_handoff_keeps_prompt_commands_files_and_conversation()
    {
        var id = "11111111-2222-3333-4444-5555555555f1";
        const string ts = "2026-10-29T10:00:00.000Z";
        object Asst(params object[] blocks) => new { type = "assistant", sessionId = id, timestamp = ts, message = new { role = "assistant", content = blocks } };
        object Result(string text) => new { type = "user", sessionId = id, timestamp = ts, message = new { role = "user", content = new object[] { new { type = "tool_result", tool_use_id = "t", content = text } } } };
        var lines = new List<string>
        {
            J(new { type = "user", isMeta = true, sessionId = id, timestamp = ts, cwd = Project, message = new { role = "user", content = "Caveat: the messages below were generated by the user while running local commands. DO NOT respond to these messages." } }),
            J(new { type = "user", sessionId = id, timestamp = ts, cwd = Project, message = new { role = "user", content = Prompt } }),
            J(Asst(new { type = "text", text = Plan })),
            J(Asst(new { type = "tool_use", id = "t1", name = "Bash", input = new { command = Command, description = "Run tests" } })),
            J(Result("TOOL-OUTPUT Failed: 1")),
            J(Asst(new { type = "tool_use", id = "t2", name = "Edit", input = new { file_path = Edited, old_string = "a", new_string = "b", replace_all = false } })),
            J(Result("TOOL-OUTPUT edited")),
            J(Asst(new { type = "text", text = Done })),
        };
        for (var i = 0; i < TailTools; i++)
        {
            lines.Add(J(Asst(new { type = "tool_use", id = $"x{i}", name = "TodoWrite", input = new { todos = new[] { new { content = $"todo {i}", status = "done" } } } })));
            lines.Add(J(Result("TOOL-OUTPUT todo ok")));
        }
        SessionFixtures.WriteLines(Path.Combine(Home, ".claude", "projects", "C--project", id + ".jsonl"), [.. lines]);

        AssertHandoff(Handoff(new ClaudeAdapter(Home)));
    }

    [Fact]
    public void Codex_session_handoff_keeps_prompt_commands_files_and_conversation()
    {
        var id = "00000000-0000-7000-8000-0000000000f1";
        const string ts = "2026-10-29T10:00:00.000Z";
        string Ri(object payload) => J(new { timestamp = ts, type = "response_item", payload });
        string Msg(string role, string text) => Ri(new { type = "message", role, content = new[] { new { type = role == "assistant" ? "output_text" : "input_text", text } } });
        var lines = new List<string>
        {
            J(new { timestamp = ts, type = "session_meta", payload = new { id, timestamp = ts, cwd = Project, originator = "codex-tui" } }),
            Msg("developer", "<permissions instructions>sandboxed</permissions instructions>"),
            Msg("user", "# AGENTS.md instructions for " + Project + "\n\nBe careful."),
            Msg("user", "<environment_context>\n  <cwd>" + Project + "</cwd>\n</environment_context>"),
            Msg("user", Prompt),
            Msg("assistant", Plan),
            Ri(new { type = "custom_tool_call", name = "exec", call_id = "c1", status = "completed",
                input = "const r = await tools.exec_command({cmd: " + JsonSerializer.Serialize(Command) + ", yield_time_ms: 10000});\ntext(r.output);" }),
            Ri(new { type = "custom_tool_call_output", call_id = "c1", output = new[] { new { type = "input_text", text = "TOOL-OUTPUT Failed: 1" } } }),
            Ri(new { type = "custom_tool_call", name = "apply_patch", call_id = "c2", status = "completed",
                input = "*** Begin Patch\n*** Update File: " + Edited + "\n@@\n-a\n+b\n*** End Patch" }),
            Ri(new { type = "custom_tool_call_output", call_id = "c2", output = "TOOL-OUTPUT Success." }),
            Msg("assistant", Done),
        };
        for (var i = 0; i < TailTools; i++)
        {
            lines.Add(Ri(new { type = "function_call", name = "update_plan", call_id = $"p{i}", arguments = J(new { plan = new[] { new { step = $"s{i}", status = "completed" } } }) }));
            lines.Add(Ri(new { type = "function_call_output", call_id = $"p{i}", output = "TOOL-OUTPUT Plan updated" }));
        }
        SessionFixtures.WriteLines(Path.Combine(Home, ".codex", "sessions", "2026", "10", "29", $"rollout-2026-10-29T10-00-00-{id}.jsonl"), [.. lines]);

        AssertHandoff(Handoff(new CodexAdapter(Home)));
    }

    [Fact]
    public void Copilot_session_handoff_keeps_prompt_commands_files_and_conversation()
    {
        var id = "00000000-0000-4000-8000-0000000000f1";
        const string ts = "2026-10-29T10:00:00.000Z";
        var n = 0;
        string Ev(string type, object data) => J(new { type, data, id = $"e{++n}", timestamp = ts, parentId = n == 1 ? null : $"e{n - 1}" });
        var dir = Path.Combine(Home, ".copilot", "session-state", id);
        Directory.CreateDirectory(dir);
        File.WriteAllText(Path.Combine(dir, "workspace.yaml"), $"id: {id}\ncwd: {Project}\nupdated_at: {ts}\n");
        var lines = new List<string>
        {
            Ev("session.start", new { sessionId = id, context = new { cwd = Project } }),
            Ev("system.message", new { role = "system", content = "You are a helpful agent." }),
            Ev("user.message", new { content = Prompt, transformedContent = "<x>" + Prompt }),
            Ev("assistant.message", new { messageId = "m1", content = Plan, toolRequests = Array.Empty<object>() }),
            Ev("tool.execution_start", new { toolCallId = "t1", toolName = "powershell", arguments = new { command = Command, description = "Run tests", initial_wait = 60 } }),
            Ev("tool.execution_complete", new { toolCallId = "t1", success = true, result = new { content = "TOOL-OUTPUT Failed: 1", detailedContent = "TOOL-OUTPUT" } }),
            Ev("tool.execution_start", new { toolCallId = "t2", toolName = "edit", arguments = new { path = Edited, old_str = "a", new_str = "b" } }),
            Ev("tool.execution_complete", new { toolCallId = "t2", success = true, result = new { content = "TOOL-OUTPUT edited" } }),
            Ev("assistant.message", new { messageId = "m2", content = Done, toolRequests = Array.Empty<object>() }),
        };
        for (var i = 0; i < TailTools; i++)
        {
            lines.Add(Ev("tool.execution_start", new { toolCallId = $"r{i}", toolName = "report_intent", arguments = new { intent = $"Checking {i}" } }));
            lines.Add(Ev("tool.execution_complete", new { toolCallId = $"r{i}", success = true, result = new { content = "TOOL-OUTPUT Intent logged" } }));
        }
        SessionFixtures.WriteLines(Path.Combine(dir, "events.jsonl"), [.. lines]);

        AssertHandoff(Handoff(new CopilotAdapter(Home)));
    }
}
